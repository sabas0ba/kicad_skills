#!/usr/bin/env bash
# Wire this repository's skills into the project that contains it as a submodule.
#
#   git submodule add https://github.com/sabas0ba/kicad_skills tools/kicad_skills
#   ./tools/kicad_skills/bin/install-skills.sh
#
# It creates two things in the parent project:
#
#   .claude/skills/<skill>   -> symlink into the submodule (so `git submodule
#                               update` upgrades the skills with no re-install)
#   bin/eda.sh               -> a shim that runs the submodule's wrapper, so the
#                               `./bin/eda.sh ...` commands in the skill docs
#                               work verbatim from the parent project root
#
# Options:
#   --copy         copy the skills instead of symlinking (vendoring, Windows)
#   --force        overwrite entries that already exist
#   --no-shim      skip bin/eda.sh
#   --uninstall    remove what this script installed
#   --target DIR   install into DIR (default: the git root above the submodule)
set -euo pipefail

SOURCE_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MODE=symlink
FORCE=0
SHIM=1
ACTION=install
TARGET=""

while [ $# -gt 0 ]; do
    case "$1" in
        --copy) MODE=copy ;;
        --force) FORCE=1 ;;
        --no-shim) SHIM=0 ;;
        --uninstall) ACTION=uninstall ;;
        --target) TARGET="${2:?--target needs a directory}"; shift ;;
        -h|--help) sed -n '2,20p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "error: unknown option $1" >&2; exit 2 ;;
    esac
    shift
done

# ---- where does the parent project live -----------------------------------
if [ -z "$TARGET" ]; then
    # The submodule is a git repository of its own, so ask for the superproject
    # first and only fall back to the directory above.
    TARGET="$(git -C "$SOURCE_ROOT" rev-parse --show-superproject-working-tree 2>/dev/null || true)"
    [ -z "$TARGET" ] && TARGET="$(cd "$SOURCE_ROOT/.." && pwd)"
fi
TARGET="$(cd "$TARGET" && pwd)"

if [ "$TARGET" = "$SOURCE_ROOT" ]; then
    echo "error: the target is this repository itself - nothing to install." >&2
    echo "       Add it to another project as a submodule, or pass --target DIR." >&2
    exit 1
fi

SKILL_SRC="$SOURCE_ROOT/.claude/skills"
SKILL_DST="$TARGET/.claude/skills"
[ -d "$SKILL_SRC" ] || { echo "error: no skills in $SKILL_SRC" >&2; exit 1; }

# Path of the submodule relative to the parent, for relocatable symlinks.
case "$SOURCE_ROOT" in
    "$TARGET"/*) SUB_REL="${SOURCE_ROOT#"$TARGET"/}" ;;
    *) SUB_REL="" ;;  # not nested: fall back to absolute links
esac

# ---- uninstall -------------------------------------------------------------
if [ "$ACTION" = uninstall ]; then
    for skill in "$SKILL_SRC"/*/; do
        name="$(basename "$skill")"
        rm -rf "${SKILL_DST:?}/$name"
        echo "removed .claude/skills/$name"
    done
    if [ -f "$TARGET/bin/eda.sh" ] && grep -q "install-skills.sh" "$TARGET/bin/eda.sh" 2>/dev/null; then
        rm -f "$TARGET/bin/eda.sh"
        echo "removed bin/eda.sh"
    fi
    rmdir "$SKILL_DST" "$TARGET/.claude" 2>/dev/null || true
    exit 0
fi

# ---- install ---------------------------------------------------------------
mkdir -p "$SKILL_DST"
for skill in "$SKILL_SRC"/*/; do
    name="$(basename "$skill")"
    dst="$SKILL_DST/$name"
    if [ -e "$dst" ] || [ -L "$dst" ]; then
        if [ "$FORCE" != 1 ]; then
            echo "skip .claude/skills/$name (already exists; --force to replace)"
            continue
        fi
        rm -rf "$dst"
    fi
    if [ "$MODE" = copy ]; then
        cp -R "$skill" "$dst"
    elif [ -n "$SUB_REL" ]; then
        ln -s "../../$SUB_REL/.claude/skills/$name" "$dst"
    else
        ln -s "$skill" "$dst"
    fi
    echo "installed .claude/skills/$name ($MODE)"
done

if [ "$SHIM" = 1 ]; then
    mkdir -p "$TARGET/bin"
    shim="$TARGET/bin/eda.sh"
    if { [ ! -e "$shim" ] || [ "$FORCE" = 1 ]; }; then
        # Relative when nested, so the shim survives the project being moved.
        if [ -n "$SUB_REL" ]; then
            wrapper='$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)'"/$SUB_REL/bin/eda.sh"
        else
            wrapper="$SOURCE_ROOT/bin/eda.sh"
        fi
        cat > "$shim" <<EOF
#!/usr/bin/env bash
# Generated by kicad_skills/bin/install-skills.sh - runs the toolkit container.
# Regenerate with: $SUB_REL/bin/install-skills.sh --force
set -euo pipefail
exec "$wrapper" "\$@"
EOF
        chmod +x "$shim"
        echo "installed bin/eda.sh (shim)"
    else
        echo "skip bin/eda.sh (already exists; --force to replace)"
    fi
fi

cat <<EOF

Done. Next:
  ./bin/eda.sh doctor          builds the image on first use, then reports versions
  ./bin/eda.sh report . -o build/report

Commit .claude/skills and bin/eda.sh so the rest of the team gets them too.
EOF
