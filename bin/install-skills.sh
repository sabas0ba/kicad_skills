#!/usr/bin/env bash
# Wire this repository into a project, or into this checkout itself.
#
#   git submodule add https://github.com/sabas0ba/kicad_skills tools/kicad_skills
#   ./tools/kicad_skills/bin/install-skills.sh
#
# The guides live in docs/guides/ as ordinary Markdown - that is the source of
# truth, and nothing has to be installed to read them. This script exists for
# tools that want them in a particular layout, and for the CLI shim:
#
#   bin/eda.sh               -> a shim that runs the toolkit's wrapper, so the
#                               `./bin/eda.sh ...` commands in the docs work
#                               verbatim from the project root
#   .agents/skills/<name>/SKILL.md -> each guide in the tool-neutral Agent
#                                    Skills layout used by Codex and compatible
#                                    assistants
#   .claude/skills/<name>/SKILL.md -> the same guides for Claude Code
#
# Both layouts are installed by default. Point --dest somewhere else to install
# only that custom layout, or pass --no-guides if you only want the CLI.
#
# Options:
#   --dest DIR     install only into target-relative DIR (default: both layouts)
#   --copy         copy the guides instead of symlinking (vendoring, Windows)
#   --force        overwrite file and symlink entries that already exist
#   --no-shim      skip bin/eda.sh when installing or uninstalling
#   --no-guides    skip guides when installing or uninstalling
#   --uninstall    remove what this script installed
#   --target DIR   install into DIR (default: the git root above the submodule,
#                  or this repository itself when it is not a submodule)
set -euo pipefail

SOURCE_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
MODE=symlink
FORCE=0
SHIM=1
GUIDES=1
ACTION=install
TARGET=""
DEST=""

while [ $# -gt 0 ]; do
    case "$1" in
        --copy) MODE=copy ;;
        --force) FORCE=1 ;;
        --no-shim) SHIM=0 ;;
        --no-guides) GUIDES=0 ;;
        --dest) DEST="${2:?--dest needs a directory}"; shift ;;
        --uninstall) ACTION=uninstall ;;
        --target) TARGET="${2:?--target needs a directory}"; shift ;;
        -h|--help) sed -n '2,30p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "error: unknown option $1" >&2; exit 2 ;;
    esac
    shift
done

# ---- where does the project live ------------------------------------------
if [ -z "$TARGET" ]; then
    # As a submodule, install into the superproject; standalone, into this
    # checkout, so that working *on* the toolkit still gets the skills.
    TARGET="$(git -C "$SOURCE_ROOT" rev-parse --show-superproject-working-tree 2>/dev/null || true)"
    [ -z "$TARGET" ] && TARGET="$SOURCE_ROOT"
fi
TARGET="$(cd "$TARGET" && pwd -P)"
SELF_INSTALL=0
[ "$TARGET" = "$SOURCE_ROOT" ] && SELF_INSTALL=1

GUIDE_SRC="$SOURCE_ROOT/docs/guides"

normalize_destination() {
    local raw="$1" normalized="" part
    local -a parts
    case "$raw" in
        /*|[A-Za-z]:*)
            echo "error: --dest must be relative to the target: $raw" >&2
            return 1
            ;;
        *\\*)
            echo "error: --dest must use '/' separators: $raw" >&2
            return 1
            ;;
    esac
    IFS=/ read -r -a parts <<< "$raw"
    for part in "${parts[@]}"; do
        case "$part" in
            ""|.) continue ;;
            ..)
                echo "error: --dest must not contain '..': $raw" >&2
                return 1
                ;;
            *) normalized="${normalized:+$normalized/}$part" ;;
        esac
    done
    if [ -z "$normalized" ]; then
        echo "error: --dest must name a directory below the target" >&2
        return 1
    fi
    printf '%s\n' "$normalized"
}

if [ -n "$DEST" ]; then
    DEST="$(normalize_destination "$DEST")" || exit 1
fi

if [ "$ACTION" = install ] && [ "$GUIDES" = 1 ] && [ ! -d "$GUIDE_SRC" ]; then
    echo "error: no guides in $GUIDE_SRC" >&2
    exit 1
fi

if [ -n "$DEST" ]; then
    DESTINATIONS=("$DEST")
else
    DESTINATIONS=(".agents/skills" ".claude/skills")
fi

INSTALL_MARKER=".eda-toolkit-installed"
INSTALL_MARKER_CONTENT="created by kicad_skills/bin/install-skills.sh"
SHIM_MARKER_CONTENT="# Generated by kicad_skills/bin/install-skills.sh - runs the toolkit container."

# Path of the toolkit relative to the project, for relocatable symlinks.
if [ "$SELF_INSTALL" = 1 ]; then
    SUB_REL="."
else
    case "$SOURCE_ROOT" in
        "$TARGET"/*) SUB_REL="${SOURCE_ROOT#"$TARGET"/}" ;;
        *) SUB_REL="" ;;  # not nested: fall back to absolute links
    esac
fi

validate_directory_path() {
    local relative="$1" path="$TARGET" part
    local -a parts
    IFS=/ read -r -a parts <<< "$relative"
    for part in "${parts[@]}"; do
        path="$path/$part"
        if [ -L "$path" ]; then
            echo "error: path component is a symlink: ${path#"$TARGET"/}" >&2
            return 1
        fi
        if [ -e "$path" ] && [ ! -d "$path" ]; then
            echo "error: path component is not a directory: ${path#"$TARGET"/}" >&2
            return 1
        fi
    done
}

render_shim() {
    local wrapper_path installer
    if [ -n "$SUB_REL" ]; then
        printf -v wrapper_path '%q' "$SUB_REL/bin/eda.sh"
        printf -v installer '%q' "$SUB_REL/bin/install-skills.sh"
        cat <<EOF
#!/usr/bin/env bash
$SHIM_MARKER_CONTENT
# Regenerate with: $installer --force
set -euo pipefail
project_root="\$(cd "\$(dirname "\${BASH_SOURCE[0]}")/.." && pwd -P)"
exec "\$project_root"/$wrapper_path "\$@"
EOF
    else
        printf -v wrapper_path '%q' "$SOURCE_ROOT/bin/eda.sh"
        printf -v installer '%q' "$SOURCE_ROOT/bin/install-skills.sh"
        cat <<EOF
#!/usr/bin/env bash
$SHIM_MARKER_CONTENT
# Regenerate with: $installer --force
set -euo pipefail
exec $wrapper_path "\$@"
EOF
    fi
}

shim_is_owned() {
    local shim="$1"
    [ -f "$shim" ] && [ ! -L "$shim" ] &&
        [ "$(sed -n '1p' "$shim")" = '#!/usr/bin/env bash' ] &&
        [ "$(sed -n '2p' "$shim")" = "$SHIM_MARKER_CONTENT" ]
}

write_shim() {
    local shim="$1" temporary
    temporary="$(mktemp "$TARGET/bin/.eda.sh.XXXXXX")"
    if ! render_shim > "$temporary" || ! chmod 0755 "$temporary"; then
        rm -f "$temporary"
        return 1
    fi
    if ! rm -f "$shim" || ! mv "$temporary" "$shim"; then
        rm -f "$temporary"
        return 1
    fi
}

guide_names() {
    [ -d "$GUIDE_SRC" ] || return 0
    for guide in "$GUIDE_SRC"/*.md; do
        [ -e "$guide" ] || [ -L "$guide" ] || continue
        name="$(basename "$guide" .md)"
        [ "$name" = "README" ] && continue
        printf '%s\n' "$name"
    done
}

GUIDE_NAMES=()
while IFS= read -r name; do
    GUIDE_NAMES+=("$name")
done < <(guide_names)

preflight_install() {
    local dest name skill_dir dst marker
    if [ "$GUIDES" = 1 ]; then
        for dest in "${DESTINATIONS[@]}"; do
            for name in "${GUIDE_NAMES[@]}"; do
                validate_directory_path "$dest/$name" || return 1
                skill_dir="$TARGET/$dest/$name"
                dst="$skill_dir/SKILL.md"
                marker="$skill_dir/$INSTALL_MARKER"
                if [ "$FORCE" = 1 ]; then
                    if [ -d "$dst" ] && [ ! -L "$dst" ]; then
                        echo "error: cannot replace directory $dest/$name/SKILL.md" >&2
                        return 1
                    fi
                    if [ -d "$marker" ] && [ ! -L "$marker" ]; then
                        echo "error: cannot replace marker directory $dest/$name/$INSTALL_MARKER" >&2
                        return 1
                    fi
                fi
            done
        done
    fi
    if [ "$SHIM" = 1 ] && [ "$SELF_INSTALL" = 0 ]; then
        validate_directory_path bin || return 1
        if [ "$FORCE" = 1 ] && [ -d "$TARGET/bin/eda.sh" ] && [ ! -L "$TARGET/bin/eda.sh" ]; then
            echo "error: cannot replace directory bin/eda.sh" >&2
            return 1
        fi
    fi
}

uninstall_skill() {
    local dest="$1" name="$2"
    local skill_dir="$TARGET/$dest/$name"
    local marker="$skill_dir/$INSTALL_MARKER"
    local dst="$skill_dir/SKILL.md"
    if [ -L "$skill_dir" ] || { [ -e "$skill_dir" ] && [ ! -d "$skill_dir" ]; }; then
        echo "skip $dest/$name (skill directory is not a regular directory)"
        return
    fi
    if [ ! -f "$marker" ] || [ -L "$marker" ] ||
        [ "$(cat "$marker")" != "$INSTALL_MARKER_CONTENT" ]; then
        if [ -e "$dst" ] || [ -L "$dst" ]; then
            echo "skip $dest/$name (not installed by this script)"
        fi
        return
    fi
    if [ -d "$dst" ] && [ ! -L "$dst" ]; then
        echo "skip $dest/$name (SKILL.md is a directory)"
        return
    fi
    rm -f "$dst" "$marker"
    rmdir "$skill_dir" 2>/dev/null || true
    echo "removed $dest/$name"
}

# ---- uninstall -------------------------------------------------------------
if [ "$ACTION" = uninstall ]; then
    if [ "$GUIDES" = 1 ]; then
        for dest in "${DESTINATIONS[@]}"; do
            validate_directory_path "$dest" || exit 1
        done
        for dest in "${DESTINATIONS[@]}"; do
            guide_dst="$TARGET/$dest"
            uninstall_names=("${GUIDE_NAMES[@]}")
            if [ -d "$guide_dst" ]; then
                for skill_dir in "$guide_dst"/*; do
                    [ -d "$skill_dir" ] && [ ! -L "$skill_dir" ] || continue
                    marker="$skill_dir/$INSTALL_MARKER"
                    [ -e "$marker" ] || [ -L "$marker" ] || continue
                    name="${skill_dir##*/}"
                    found=0
                    for existing_name in "${uninstall_names[@]}"; do
                        [ "$existing_name" = "$name" ] && found=1 && break
                    done
                    [ "$found" = 1 ] || uninstall_names+=("$name")
                done
            fi
            for name in "${uninstall_names[@]}"; do
                uninstall_skill "$dest" "$name"
            done
            # Remove directories we created, innermost first, only while empty.
            dir="$guide_dst"
            while [ "$dir" != "$TARGET" ] && [ -d "$dir" ]; do
                rmdir "$dir" 2>/dev/null || break
                dir="$(dirname "$dir")"
            done
        done
    fi
    if [ "$SHIM" = 1 ]; then
        if [ -L "$TARGET/bin" ]; then
            echo "skip bin/eda.sh (bin is a symlink)"
        elif shim_is_owned "$TARGET/bin/eda.sh"; then
            rm -f "$TARGET/bin/eda.sh"
            echo "removed bin/eda.sh"
        fi
    fi
    exit 0
fi

# ---- install ---------------------------------------------------------------
preflight_install

if [ "$GUIDES" = 1 ]; then
    for dest in "${DESTINATIONS[@]}"; do
        guide_dst="$TARGET/$dest"
        # Levels up from guide_dst/<name>/ to TARGET, for relative links.
        IFS=/ read -r -a dest_parts <<< "$dest"
        up="../"
        for _ in "${dest_parts[@]}"; do up="../$up"; done
        for name in "${GUIDE_NAMES[@]}"; do
            skill_dir="$guide_dst/$name"
            dst="$skill_dir/SKILL.md"
            marker="$skill_dir/$INSTALL_MARKER"
            # Resolve marker collisions before creating or replacing the skill.
            # Removing a marker symlink is safe; redirecting through it is not.
            if [ -e "$marker" ] || [ -L "$marker" ]; then
                if [ "$FORCE" = 1 ]; then
                    rm -f "$marker"
                elif [ ! -e "$dst" ] && [ ! -L "$dst" ]; then
                    echo "skip $dest/$name (ownership marker already exists; --force to replace)"
                    continue
                fi
            fi
            if [ -e "$dst" ] || [ -L "$dst" ]; then
                if [ "$FORCE" != 1 ]; then
                    if [ ! -e "$marker" ] && [ ! -L "$marker" ] &&
                        [ -L "$dst" ] && [ "$dst" -ef "$GUIDE_SRC/$name.md" ]; then
                        printf '%s\n' "$INSTALL_MARKER_CONTENT" > "$marker"
                        echo "migrated $dest/$name (legacy symlink)"
                    else
                        echo "skip $dest/$name (already exists; --force to replace)"
                    fi
                    continue
                fi
                rm -f "$dst"
            fi
            mkdir -p "$skill_dir"
            if [ "$MODE" = copy ]; then
                cp -L "$GUIDE_SRC/$name.md" "$dst"
            elif [ -n "$SUB_REL" ]; then
                ln -s "$up$SUB_REL/docs/guides/$name.md" "$dst"
            else
                ln -s "$GUIDE_SRC/$name.md" "$dst"
            fi
            printf '%s\n' "$INSTALL_MARKER_CONTENT" > "$marker"
            echo "installed $dest/$name/SKILL.md ($MODE)"
        done
    done
fi

if [ "$SHIM" = 1 ] && [ "$SELF_INSTALL" = 0 ]; then
    mkdir -p "$TARGET/bin"
    shim="$TARGET/bin/eda.sh"
    if { [ ! -e "$shim" ] && [ ! -L "$shim" ]; } || [ "$FORCE" = 1 ]; then
        write_shim "$shim"
        echo "installed bin/eda.sh (shim)"
    else
        echo "skip bin/eda.sh (already exists; --force to replace)"
    fi
fi

if [ "$SELF_INSTALL" = 1 ]; then
    cat <<EOF

Done - the skill layouts now mirror docs/guides/ for this checkout. They are
git-ignored: docs/guides/ is the source of truth, these are only adapters.
EOF
else
    cat <<EOF

Done. Next:
  ./bin/eda.sh doctor          builds the image on first use, then reports versions
  ./bin/eda.sh report . -o build/report

Commit bin/eda.sh and any skill adapters your team chooses to track.
EOF
fi
