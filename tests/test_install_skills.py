@pytest.mark.parametrize("action", ["install", "uninstall"])
def test_a_symlinked_skill_directory_is_never_traversed(project, action):
    target, submodule = project
    destination = "custom-skills"
    name = GUIDES[0]
    layout = target / destination
    layout.mkdir()
    external_skill = target.parent / f"external-skill-{action}"
