    external_marker = external_skill / ".eda-toolkit-installed"
    external_marker.write_text(INSTALL_MARKER_CONTENT)
    external_adapter = external_skill / "SKILL.md"
    external_adapter.write_text(USER_SKILL_CONTENT)
    (layout / name).symlink_to(external_skill, target_is_directory=True)

    arguments = ["--dest", destination, "--no-shim"]
    if action == "install":
        arguments.append("--force")
        with pytest.raises(subprocess.CalledProcessError):
            install(submodule, target, *arguments)
    else:
        arguments.append("--uninstall")
        install(submodule, target, *arguments)

    assert external_marker.read_text() == INSTALL_MARKER_CONTENT
    assert external_adapter.read_text() == USER_SKILL_CONTENT


